ALTER TABLE categorias ADD (
    creado_por VARCHAR2(50 CHAR),
    modificado_por VARCHAR2(50 CHAR)
);

ALTER TABLE productos ADD (
    creado_por VARCHAR2(50 CHAR),
    modificado_por VARCHAR2(50 CHAR)
);

ALTER TABLE clientes ADD (
    creado_por VARCHAR2(50 CHAR),
    modificado_por VARCHAR2(50 CHAR)
);

ALTER TABLE ventas ADD (
    creado_por VARCHAR2(50 CHAR)
);

CREATE TABLE auditoria_eventos (
    id         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    fecha      TIMESTAMP(6) NOT NULL,
    usuario    VARCHAR2(50 CHAR) NOT NULL,
    accion     VARCHAR2(40 CHAR) NOT NULL,
    entidad    VARCHAR2(40 CHAR) NOT NULL,
    entidad_id NUMBER(19,0),
    detalle    VARCHAR2(500 CHAR),
    request_id VARCHAR2(36 CHAR),
    CONSTRAINT pk_auditoria_eventos PRIMARY KEY (id)
);

CREATE INDEX ix_auditoria_fecha ON auditoria_eventos (fecha);
CREATE INDEX ix_auditoria_usuario ON auditoria_eventos (usuario, fecha);

-- Crea el indice de productos solo si el nombre aun no existe.
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM user_indexes
     WHERE index_name = 'IX_PRODUCTOS_NOMBRE';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_productos_nombre ON productos (nombre)';
    END IF;
END;
/
